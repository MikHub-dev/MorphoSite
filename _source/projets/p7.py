import math


def _N(x):
    return 0.5 * (1 + math.erf(x / math.sqrt(2)))


def _call(S, K=100, T=0.5, s=0.2, r=0.02):
    if S <= 0:
        return 0.0
    d1 = (math.log(S / K) + (r + s * s / 2) * T) / (s * math.sqrt(T))
    return S * _N(d1) - K * math.exp(-r * T) * _N(d1 - s * math.sqrt(T))


