def _sir(days=120, beta=0.3, gamma=0.1, N=1000, S=990.0, I=10.0, R=0.0):
    out = [(0, S, I, R)]
    for d in range(1, days + 1):
        dS = -beta * S * I / N
        dR = gamma * I
        S, I, R = S + dS, I - dS - dR, R + dR
        out.append((d, S, I, R))
    return out


