def _euler(a=0.5, dt=0.5, T=4.0, y0=1.0):
    pts, y, t = [(0, y0)], y0, 0.0
    while t < T - 1e-9:
        y, t = y * (1 + a * dt), t + dt
        pts.append((t, y))
    return pts


